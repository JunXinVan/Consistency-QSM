#!/usr/bin/env python3
"""
Canonical gt_core cache generator for Stage 4 v3 / v5 training.

This generator is intentionally separate from the legacy teacher-refinement cache
pipeline. It writes the manifest/shard format expected by:

- stage4_pcct_cg.py
- stage4_build_hard_scores.py
- stage4_infer.py (cache-side evaluation)

Design choices:
- source split defaults to train-only
- field is generated by forward dipole convolution from chi_gt
- x_init is the adjoint reconstruction of that field
- no teacher trajectories are written
- coords + subjects are preserved for audit and hard-mining
"""

from __future__ import annotations

import argparse
import json
from collections import OrderedDict
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import numpy as np
import torch

from qsm_bank_utils import (
    adjoint_field_to_chi,
    create_dipole_kernel,
    forward_field_from_chi,
    parse_triplet,
    seed_everything,
)


CACHE_FORMAT = "qsm_stage4_v3_cache"
BANK_MODE = "gt_core"


def atomic_save_json(path: Path, payload: dict) -> None:
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    tmp_path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    tmp_path.replace(path)


def atomic_save_npy(path: Path, array: np.ndarray) -> None:
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    with tmp_path.open("wb") as handle:
        np.save(handle, array, allow_pickle=False)
    tmp_path.replace(path)


def manifest_path_for_rank(output_dir: Path, rank: int) -> Path:
    return output_dir / f"manifest_rank_{rank}.json"


def compute_rank_target(bank_size: int, rank: int, world_size: int) -> int:
    base = bank_size // world_size
    remainder = bank_size % world_size
    return base + (1 if rank < remainder else 0)


def parse_subject_list(value: str | None) -> tuple[str, ...]:
    if value is None:
        return ()
    tokens: list[str] = []
    seen: set[str] = set()
    for raw_part in value.split(","):
        token = raw_part.strip().strip("/")
        if not token or token in seen:
            continue
        seen.add(token)
        tokens.append(token)
    return tuple(tokens)


def subject_match_tokens(volume_path: Path, data_dir: Path) -> set[str]:
    try:
        rel_parent = volume_path.parent.relative_to(data_dir)
    except ValueError:
        rel_parent = volume_path.parent
    parts = [part for part in rel_parent.parts if part not in {"."}]
    tokens = {volume_path.parent.name, str(rel_parent).strip("/")}
    if parts:
        tokens.add(parts[-1])
        tokens.add("/".join(parts))
    return {token for token in tokens if token}


def filter_files_by_subjects(
    files: Sequence[Path],
    data_dir: Path,
    subject_allowlist: Sequence[str],
    subject_denylist: Sequence[str],
) -> list[Path]:
    allow = {token.strip("/").strip() for token in subject_allowlist if token.strip()}
    deny = {token.strip("/").strip() for token in subject_denylist if token.strip()}
    filtered: list[Path] = []
    for path in files:
        tokens = subject_match_tokens(path, data_dir)
        if allow and not any(token in allow for token in tokens):
            continue
        if deny and any(token in deny for token in tokens):
            continue
        filtered.append(path)
    return filtered


def collect_cosmos_files(data_dir: Path, split: str) -> list[Path]:
    if not data_dir.exists():
        raise FileNotFoundError(f"Data directory does not exist: {data_dir}")

    if split == "all":
        roots = [root for root in (data_dir / "train", data_dir / "test") if root.exists()]
        if not roots:
            roots = [data_dir]
    else:
        root = data_dir / split
        if not root.exists():
            raise FileNotFoundError(f"Requested split directory does not exist: {root}")
        roots = [root]

    files: list[Path] = []
    for root in roots:
        files.extend(sorted(root.rglob("cosmos*.nii*")))

    if not files:
        raise FileNotFoundError(f"No cosmos*.nii* files found for split={split!r} under {data_dir}")
    return files


def load_nifti(path: Path) -> np.ndarray:
    try:
        import nibabel as nib
    except ModuleNotFoundError as exc:
        raise ModuleNotFoundError("nibabel is required for gt_core cache generation.") from exc
    return np.asarray(nib.load(str(path)).get_fdata(), dtype=np.float32)


def load_existing_manifest(output_dir: Path, rank: int) -> dict:
    path = manifest_path_for_rank(output_dir, rank)
    if not path.exists():
        return {"format": CACHE_FORMAT, "rank": rank, "bank_mode": BANK_MODE, "shards": []}

    manifest = json.loads(path.read_text(encoding="utf-8"))
    if manifest.get("format") != CACHE_FORMAT:
        raise RuntimeError(
            f"Found incompatible manifest format {manifest.get('format')!r} in {path}; expected {CACHE_FORMAT!r}"
        )
    if manifest.get("bank_mode") != BANK_MODE:
        raise RuntimeError(
            f"Found incompatible bank_mode {manifest.get('bank_mode')!r} in {path}; expected {BANK_MODE!r}"
        )

    valid_shards = []
    for shard in manifest.get("shards", []):
        files = [output_dir / rel_path for rel_path in shard["files"].values()]
        if not all(path.exists() for path in files):
            continue
        field = np.load(output_dir / shard["files"]["field"], mmap_mode="r")
        count = int(field.shape[0])
        if count != int(shard["count"]):
            continue
        valid_shards.append(shard)
    manifest["shards"] = valid_shards
    return manifest


def ensure_manifest_compatible(manifest: dict, expected: dict) -> None:
    if not manifest.get("shards"):
        return

    mismatches = []
    for key, expected_value in expected.items():
        if key not in manifest:
            continue
        if manifest[key] != expected_value:
            mismatches.append(f"{key}: existing={manifest[key]!r}, expected={expected_value!r}")
    if mismatches:
        raise RuntimeError(
            "Existing gt_core cache manifest is incompatible with requested configuration. "
            + "; ".join(mismatches)
        )


@dataclass
class VolumeRecord:
    subject_id: str
    source_path: Path
    chi_gt: np.ndarray
    mask: np.ndarray
    field: np.ndarray
    x_init: np.ndarray
    shape: tuple[int, int, int]
    valid_origin_max: tuple[int, int, int]


class VolumeCache:
    def __init__(
        self,
        patch_size: Sequence[int],
        voxel_size: Sequence[float],
        b0_dir: Sequence[float],
        device: torch.device,
        mask_threshold: float,
        cache_size: int,
    ) -> None:
        self.patch_size = tuple(int(v) for v in patch_size)
        self.voxel_size = tuple(float(v) for v in voxel_size)
        self.b0_dir = tuple(float(v) for v in b0_dir)
        self.device = device
        self.mask_threshold = float(mask_threshold)
        self.cache_size = max(int(cache_size), 1)
        self._cache: OrderedDict[str, VolumeRecord] = OrderedDict()

    def load(self, volume_path: Path) -> VolumeRecord:
        key = str(volume_path.resolve())
        if key in self._cache:
            record = self._cache.pop(key)
            self._cache[key] = record
            return record

        chi_gt = load_nifti(volume_path)
        mask = (np.abs(chi_gt) > self.mask_threshold).astype(np.float32)
        if chi_gt.ndim != 3:
            raise ValueError(f"Expected 3D chi_gt volume, got {volume_path} with shape {chi_gt.shape}")

        kernel = create_dipole_kernel(
            chi_gt.shape,
            voxel_size=self.voxel_size,
            b0_dir=self.b0_dir,
            device=self.device,
            dtype=torch.float32,
        )

        chi_t = torch.from_numpy(chi_gt).to(self.device, dtype=torch.float32).unsqueeze(0).unsqueeze(0)
        mask_t = torch.from_numpy(mask).to(self.device, dtype=torch.float32).unsqueeze(0).unsqueeze(0)
        with torch.no_grad():
            field_t = forward_field_from_chi(chi_t, kernel, mask=mask_t)
            x_init_t = adjoint_field_to_chi(field_t, kernel, mask=mask_t)

        valid_origin_max = tuple(dim - patch for dim, patch in zip(chi_gt.shape, self.patch_size))
        if any(v < 0 for v in valid_origin_max):
            raise ValueError(
                f"Patch size {self.patch_size} exceeds volume shape {chi_gt.shape} for {volume_path}"
            )

        record = VolumeRecord(
            subject_id=f"{volume_path.parent.name}/{volume_path.name}",
            source_path=volume_path,
            chi_gt=chi_gt.astype(np.float32),
            mask=mask.astype(np.float32),
            field=field_t.squeeze(0).squeeze(0).detach().cpu().numpy().astype(np.float32),
            x_init=x_init_t.squeeze(0).squeeze(0).detach().cpu().numpy().astype(np.float32),
            shape=tuple(int(v) for v in chi_gt.shape),
            valid_origin_max=tuple(int(v) for v in valid_origin_max),
        )
        self._cache[key] = record
        while len(self._cache) > self.cache_size:
            self._cache.popitem(last=False)
        return record


def extract_patch(volume: np.ndarray, origin: Sequence[int], patch_size: Sequence[int]) -> np.ndarray:
    d0, h0, w0 = (int(v) for v in origin)
    pd, ph, pw = (int(v) for v in patch_size)
    return np.array(volume[d0 : d0 + pd, h0 : h0 + ph, w0 : w0 + pw], copy=True)


def save_shard(output_dir: Path, rank: int, shard_index: int, samples: list[dict]) -> dict:
    prefix = f"cache_rank_{rank}_shard{shard_index:04d}"
    file_map = {
        "field": f"{prefix}_field.npy",
        "mask": f"{prefix}_mask.npy",
        "chi_gt": f"{prefix}_chi_gt.npy",
        "x_init": f"{prefix}_x_init.npy",
        "sample_id": f"{prefix}_sample_id.npy",
        "coords": f"{prefix}_coords.npy",
        "subjects": f"{prefix}_subjects.npy",
    }
    arrays = {
        "field": np.stack([item["field"] for item in samples]).astype(np.float16),
        "mask": np.stack([item["mask"] for item in samples]).astype(np.uint8),
        "chi_gt": np.stack([item["chi_gt"] for item in samples]).astype(np.float16),
        "x_init": np.stack([item["x_init"] for item in samples]).astype(np.float16),
        "sample_id": np.asarray([item["sample_id"] for item in samples], dtype=np.int64),
        "coords": np.asarray([item["origin"] for item in samples], dtype=np.int16),
        "subjects": np.asarray([item["subject_id"] for item in samples], dtype="U128"),
    }
    for key, rel_path in file_map.items():
        atomic_save_npy(output_dir / rel_path, arrays[key])

    shard_meta = {
        "prefix": prefix,
        "count": int(arrays["sample_id"].shape[0]),
        "format": CACHE_FORMAT,
        "has_teacher_endpoint": False,
        "files": file_map,
    }
    atomic_save_json(output_dir / f"{prefix}_meta.json", shard_meta)
    return shard_meta


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=str, required=True)
    parser.add_argument("--output-dir", type=str, required=True)
    parser.add_argument("--split", choices=["train", "test", "all"], default="train")
    parser.add_argument(
        "--subject-allowlist",
        type=str,
        default=None,
        help="Optional comma-separated subject filter, e.g. subject1,subject2 or train/subject1.",
    )
    parser.add_argument(
        "--subject-denylist",
        type=str,
        default=None,
        help="Optional comma-separated subject exclude filter.",
    )
    parser.add_argument("--stage3-ckpt", type=str, default=None, help="Recorded for provenance; not used by adjoint x_init.")
    parser.add_argument("--bank-size", type=int, default=15000)
    parser.add_argument("--rank", type=int, default=0)
    parser.add_argument("--world-size", type=int, default=1)
    parser.add_argument("--patch-size", type=str, default="64,64,64")
    parser.add_argument("--save-every", type=int, default=128)
    parser.add_argument("--mask-threshold", type=float, default=1e-3)
    parser.add_argument("--min-mask-voxels", type=int, default=5000)
    parser.add_argument("--voxel-size", type=str, default="1,1,1")
    parser.add_argument("--b0-dir", type=str, default="0,0,1")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--cache-size", type=int, default=2)
    parser.add_argument("--x-init-mode", choices=["adjoint", "adjoint_noise"], default="adjoint")
    parser.add_argument("--x-init-noise-std", type=float, default=0.0)
    parser.add_argument("--max-attempt-multiplier", type=int, default=50)
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    return parser


def main() -> None:
    args = build_parser().parse_args()
    if args.bank_size < 1:
        raise ValueError("--bank-size must be >= 1")
    if args.save_every < 1:
        raise ValueError("--save-every must be >= 1")
    if args.min_mask_voxels < 1:
        raise ValueError("--min-mask-voxels must be >= 1")
    if args.x_init_noise_std < 0:
        raise ValueError("--x-init-noise-std must be >= 0")

    patch_size = parse_triplet(args.patch_size, int)
    voxel_size = parse_triplet(args.voxel_size, float)
    b0_dir = parse_triplet(args.b0_dir, float)
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    data_dir = Path(args.data_dir).expanduser().resolve()
    subject_allowlist = parse_subject_list(args.subject_allowlist)
    subject_denylist = parse_subject_list(args.subject_denylist)
    seed_everything(int(args.seed) + int(args.rank))
    rng = np.random.default_rng(int(args.seed) + int(args.rank))
    device = torch.device(args.device)

    all_files = collect_cosmos_files(data_dir, split=args.split)
    all_files = filter_files_by_subjects(
        all_files,
        data_dir=data_dir,
        subject_allowlist=subject_allowlist,
        subject_denylist=subject_denylist,
    )
    if not all_files:
        raise FileNotFoundError(
            "No cosmos*.nii* files remained after subject filtering. "
            f"split={args.split!r}, allowlist={list(subject_allowlist)!r}, denylist={list(subject_denylist)!r}"
        )
    my_files = all_files[int(args.rank) :: int(args.world_size)]
    if not my_files:
        raise RuntimeError(
            f"Rank {args.rank} has no files assigned. Found {len(all_files)} total files for world_size={args.world_size}"
        )

    manifest = load_existing_manifest(output_dir, int(args.rank))
    target_samples = compute_rank_target(int(args.bank_size), int(args.rank), int(args.world_size))
    expected_manifest = {
        "format": CACHE_FORMAT,
        "bank_mode": BANK_MODE,
        "split": args.split,
        "patch_size": list(patch_size),
        "voxel_size": list(voxel_size),
        "b0_dir": list(b0_dir),
        "x_init_mode": args.x_init_mode,
        "x_init_noise_std": float(args.x_init_noise_std),
        "subject_allowlist": list(subject_allowlist),
        "subject_denylist": list(subject_denylist),
        "source_data_dir": str(data_dir),
        "stage3_ckpt": str(Path(args.stage3_ckpt).expanduser().resolve()) if args.stage3_ckpt else None,
    }
    ensure_manifest_compatible(manifest, expected_manifest)

    completed_samples = sum(int(shard["count"]) for shard in manifest["shards"])
    shard_index = len(manifest["shards"])
    next_sample_id = completed_samples
    volume_cache = VolumeCache(
        patch_size=patch_size,
        voxel_size=voxel_size,
        b0_dir=b0_dir,
        device=device,
        mask_threshold=float(args.mask_threshold),
        cache_size=int(args.cache_size),
    )

    manifest.update(
        {
            **expected_manifest,
            "rank": int(args.rank),
            "world_size": int(args.world_size),
            "target_samples": int(target_samples),
            "save_every": int(args.save_every),
            "cache_metadata": {
                "field_source": "forward_field_from_chi_gt",
                "mask_source": f"abs(chi_gt) > {float(args.mask_threshold)}",
                "generator": Path(__file__).name,
                "teacher_endpoint": False,
            },
            "shards": manifest.get("shards", []),
        }
    )
    atomic_save_json(manifest_path_for_rank(output_dir, int(args.rank)), manifest)
    run_config = {
        "entrypoint": str(Path(__file__).resolve()),
        "output_dir": str(output_dir),
        "data_dir": str(data_dir),
        "split": args.split,
        "stage3_ckpt": expected_manifest["stage3_ckpt"],
        "rank": int(args.rank),
        "world_size": int(args.world_size),
        "target_samples": int(target_samples),
        "assigned_files": [str(path) for path in my_files],
        "selected_subjects": sorted({path.parent.name for path in my_files}),
        "effective_config": {
            "format": CACHE_FORMAT,
            "bank_mode": BANK_MODE,
            "patch_size": list(patch_size),
            "voxel_size": list(voxel_size),
            "b0_dir": list(b0_dir),
            "mask_threshold": float(args.mask_threshold),
            "min_mask_voxels": int(args.min_mask_voxels),
            "x_init_mode": args.x_init_mode,
            "x_init_noise_std": float(args.x_init_noise_std),
            "device": str(device),
        },
        "cli_args": vars(args),
    }
    atomic_save_json(output_dir / f"run_config_rank_{int(args.rank)}.json", run_config)
    if int(args.rank) == 0:
        atomic_save_json(output_dir / "run_config.json", run_config)

    if completed_samples >= target_samples:
        print(f"[gt_core rank {args.rank}] cache already complete: {completed_samples}/{target_samples}")
        return

    pending: list[dict] = []
    sample_count = completed_samples
    max_attempts = max(int(args.max_attempt_multiplier) * max(target_samples, 1), 1000)
    attempts = 0
    file_cursor = 0

    print(
        f"[gt_core rank {args.rank}] split={args.split} files={len(my_files)} target={target_samples} "
        f"completed={completed_samples} patch={patch_size} device={device} "
        f"subjects={sorted({path.parent.name for path in my_files})}"
    )

    while sample_count < target_samples:
        attempts += 1
        if attempts > max_attempts:
            raise RuntimeError(
                f"Exceeded {max_attempts} sampling attempts before reaching target {target_samples}. "
                "Try lowering --min-mask-voxels or patch size."
            )

        volume_path = my_files[file_cursor % len(my_files)]
        file_cursor += 1
        record = volume_cache.load(volume_path)
        origin = [
            int(rng.integers(0, max_dim + 1)) if max_dim > 0 else 0
            for max_dim in record.valid_origin_max
        ]

        mask_patch = extract_patch(record.mask, origin, patch_size)
        if int(mask_patch.sum()) < int(args.min_mask_voxels):
            continue

        field_patch = extract_patch(record.field, origin, patch_size)
        chi_patch = extract_patch(record.chi_gt, origin, patch_size)
        x_init_patch = extract_patch(record.x_init, origin, patch_size)

        if args.x_init_mode == "adjoint_noise" and args.x_init_noise_std > 0:
            noise = rng.normal(loc=0.0, scale=float(args.x_init_noise_std), size=x_init_patch.shape).astype(np.float32)
            x_init_patch = x_init_patch + noise * mask_patch.astype(np.float32)

        pending.append(
            {
                "field": field_patch.astype(np.float32),
                "mask": mask_patch.astype(np.float32),
                "chi_gt": chi_patch.astype(np.float32),
                "x_init": x_init_patch.astype(np.float32),
                "sample_id": int(next_sample_id),
                "origin": list(origin),
                "subject_id": record.subject_id,
            }
        )
        sample_count += 1
        next_sample_id += 1

        if len(pending) >= int(args.save_every) or sample_count >= target_samples:
            shard_meta = save_shard(output_dir, int(args.rank), shard_index, pending)
            manifest["shards"].append(shard_meta)
            atomic_save_json(manifest_path_for_rank(output_dir, int(args.rank)), manifest)
            print(
                f"[gt_core rank {args.rank}] saved {shard_meta['prefix']} ({shard_meta['count']} samples) "
                f"total={sample_count}/{target_samples}"
            )
            pending = []
            shard_index += 1

    print(f"[gt_core rank {args.rank}] done. wrote {sample_count - completed_samples} new samples.")


if __name__ == "__main__":
    main()
